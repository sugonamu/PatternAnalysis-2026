
"""
COMP3710 - Alzheimer's Disease Classification Using ConvNeXt-Tiny

Prediction driver for the ADNI dataset.

Features:
- Load trained BaselineCNN or ConvNeXt-Tiny checkpoints.
- Predict a user-supplied MRI image.
- Alternatively, select an example from the held-out test split.
- Print NC/AD probabilities and predicted class.
- Save a visualization of the input image and prediction.

Class mapping:
    0 = NC (Cognitively Normal)
    1 = AD (Alzheimer's Disease)

For research demonstration only. Not a clinical diagnostic tool.
"""

import argparse
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import torch
from PIL import Image
from torchvision import transforms

from dataset import DATA_DIR, SPLITS_CSV
from modules import build_model


CLASS_NAMES = ["NC", "AD"]

CLASS_DESCRIPTIONS = {
    "NC": "Cognitively Normal",
    "AD": "Alzheimer's Disease",
}

IMAGE_SIZE = 224

IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]


def get_transform():
    """Same preprocessing as the evaluation dataset."""
    return transforms.Compose([
        transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
        transforms.ToTensor(),
        transforms.Normalize(
            mean=IMAGENET_MEAN,
            std=IMAGENET_STD,
        ),
    ])


def load_checkpoint(model_name, checkpoint_path, device):
    """Create the model and load its trained parameters."""

    if not checkpoint_path.is_file():
        raise FileNotFoundError(
            f"Checkpoint not found: {checkpoint_path}"
        )

    # Only load checkpoints generated by your own training.
    checkpoint = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=True,
    )

    if checkpoint.get("model_name") != model_name:
        raise ValueError(
            "Checkpoint model does not match --model.\n"
            f"Requested: {model_name}\n"
            f"Checkpoint: {checkpoint.get('model_name')}"
        )

    if checkpoint.get("class_mapping") != {
        "NC": 0,
        "AD": 1,
    }:
        raise ValueError(
            "Unexpected class mapping in checkpoint."
        )

    if checkpoint.get("image_size") != IMAGE_SIZE:
        raise ValueError(
            "Checkpoint image size differs from preprocessing."
        )

    # Pretrained=False prevents unnecessary ImageNet downloads.
    # The checkpoint supplies all trained model weights.
    model = build_model(
        model_name=model_name,
        num_classes=2,
        pretrained=False,
    )

    model.load_state_dict(
        checkpoint["model_state_dict"],
        strict=True,
    )

    model = model.to(device)
    model.eval()

    return model, checkpoint


def resolve_image_path(recorded_path, data_dir):
    """
    Resolve an image path recorded in splits.csv.

    Supports absolute paths and paths relative to AD_NC.
    """
    path = Path(recorded_path).expanduser()

    if path.is_absolute():
        return path

    candidates = [
        data_dir / path,
        data_dir.parent / path,
        Path.cwd() / path,
    ]

    for candidate in candidates:
        if candidate.is_file():
            return candidate

    raise FileNotFoundError(
        f"Cannot find MRI image: {recorded_path}\n"
        "Checked:\n"
        + "\n".join(str(x) for x in candidates)
    )


def select_test_image(csv_path, data_dir, test_index):
    """
    Select a specific image from the held-out test split.

    Uses the split manifest without modifying the dataset.
    """
    if not csv_path.is_file():
        raise FileNotFoundError(
            f"Split manifest not found: {csv_path}"
        )

    with csv_path.open("r", newline="") as file:
        reader = csv.DictReader(file)

        if not {"path", "split", "label"}.issubset(
            reader.fieldnames or []
        ):
            raise ValueError(
                "splits.csv needs columns: path, split, label"
            )

        test_rows = [
            row for row in reader
            if row["split"].strip().lower() == "test"
        ]

    if not test_rows:
        raise ValueError(
            "No test samples found in splits.csv"
        )

    if not (0 <= test_index < len(test_rows)):
        raise IndexError(
            f"test_index must be between 0 and "
            f"{len(test_rows) - 1}"
        )

    row = test_rows[test_index]

    image_path = resolve_image_path(
        row["path"],
        data_dir,
    )

    # Convert dataset labels into model class indices.
    # NC = 0, AD = 1
    label_mapping = {
        "NC": 0,
        "AD": 1,
    }   

    raw_label = row["label"].strip().upper()

    if raw_label not in label_mapping:
        raise ValueError(
            f"Unexpected label in splits.csv: {raw_label}"
        )

    label = label_mapping[raw_label]

    return image_path, label


def predict_image(model, image_path, device):
    """
    Predict AD/NC probabilities for one MRI slice.

    Returns original image, predicted class, probabilities.
    """
    with Image.open(image_path) as source:
        image = source.convert("RGB")

    transform = get_transform()

    image_tensor = transform(image).unsqueeze(0)
    image_tensor = image_tensor.to(device)

    with torch.inference_mode():
        logits = model(image_tensor)
        probabilities = torch.softmax(
            logits,
            dim=1,
        )[0].cpu()

    predicted_label = int(
        probabilities.argmax().item()
    )

    return (
        image,
        predicted_label,
        probabilities.tolist(),
    )


def save_visualization(
    image,
    predicted_label,
    probabilities,
    output_path,
    model_name,
    true_label=None,
):
    """Save MRI image next to an NC/AD probability chart."""

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fig, axes = plt.subplots(
        1, 2,
        figsize=(10, 4.5),
        gridspec_kw={"width_ratios": [1.2, 1]},
    )

    # Original MRI slice
    axes[0].imshow(image)
    axes[0].axis("off")
    axes[0].set_title("Input MRI Slice")

    # Predicted probabilities
    colors = ["#377EB8", "#E07A5F"]

    axes[1].barh(
        CLASS_NAMES,
        probabilities,
        color=colors,
    )

    axes[1].set_xlim(0, 1)
    axes[1].invert_yaxis()
    axes[1].set_xlabel("Predicted Probability")
    axes[1].set_title("Class Probabilities")

    for i, prob in enumerate(probabilities):
        axes[1].text(
            min(prob + 0.02, 0.91),
            i,
            f"{prob:.2%}",
            va="center",
        )

    prediction_name = CLASS_NAMES[predicted_label]

    title = (
        f"{model_name.upper()} Prediction: "
        f"{prediction_name}"
    )

    if true_label is not None:
        truth_name = CLASS_NAMES[true_label]
        status = (
            "Correct"
            if true_label == predicted_label
            else "Incorrect"
        )
        title += (
            f" | Actual: {truth_name} | {status}"
        )

    fig.suptitle(
        title,
        fontsize=13,
        y=0.98,
    )

    fig.tight_layout(
        rect=[0, 0, 1, 0.90]
    )

    fig.savefig(
        output_path,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(
        description="ADNI MRI inference driver"
    )

    parser.add_argument(
        "--model",
        choices=["baseline", "convnext"],
        default="convnext",
    )

    parser.add_argument(
        "--checkpoint",
        type=Path,
        default=None,
    )

    parser.add_argument(
        "--image",
        type=Path,
        default=None,
        help="Path to an individual MRI image",
    )

    parser.add_argument(
        "--test-index",
        type=int,
        default=0,
        help="Zero-based index of test sample (default: 0)",
    )

    parser.add_argument(
        "--csv-path",
        type=Path,
        default=SPLITS_CSV,
    )

    parser.add_argument(
        "--data-dir",
        type=Path,
        default=DATA_DIR,
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=Path("results/prediction.png"),
    )

    parser.add_argument(
        "--require-cuda",
        action="store_true",
    )

    args = parser.parse_args()

    # Select an existing trained checkpoint.
    if args.checkpoint is None:
        args.checkpoint = (
            Path("checkpoints")
            / args.model
            / "best.pth"
        )

    if torch.cuda.is_available():
        device = torch.device("cuda")
    elif torch.backends.mps.is_available():
        device = torch.device("mps")
    else:
        device = torch.device("cpu")

    if args.require_cuda and device.type != "cuda":
        raise RuntimeError(
            "CUDA not available. Run inside a GPU allocation."
        )

    print(f"Device: {device}", flush=True)

    model, checkpoint = load_checkpoint(
        args.model,
        args.checkpoint,
        device,
    )

    print(f"Model: {args.model}")
    print(f"Checkpoint: {args.checkpoint}")
    print(f"Checkpoint epoch: {checkpoint['epoch']}")

    # --------------------------------------------------------
    # Choose input image
    # --------------------------------------------------------

    true_label = None

    if args.image is not None:
        image_path = args.image.expanduser()

        if not image_path.is_file():
            raise FileNotFoundError(
                f"Image not found: {image_path}"
            )

    else:
        image_path, true_label = select_test_image(
            args.csv_path,
            args.data_dir,
            args.test_index,
        )

    print(f"\nInput image: {image_path}")

    # --------------------------------------------------------
    # Run prediction
    # --------------------------------------------------------

    (
        image,
        predicted_label,
        probabilities,
    ) = predict_image(
        model,
        image_path,
        device,
    )

    predicted_name = CLASS_NAMES[predicted_label]

    print("\n" + "=" * 45)
    print("PREDICTION RESULT")
    print("=" * 45)

    print(
        f"Predicted class: {predicted_name} "
        f"({CLASS_DESCRIPTIONS[predicted_name]})"
    )

    print(f"NC probability: {probabilities[0]:.2%}")
    print(f"AD probability: {probabilities[1]:.2%}")

    confidence = max(probabilities)

    print(f"Confidence: {confidence:.2%}")

    if true_label is not None:
        actual_name = CLASS_NAMES[true_label]
        print(f"Actual class: {actual_name}")
        print(
            "Correct prediction: ",
            predicted_label == true_label,
        )

    # --------------------------------------------------------
    # Generate visualization
    # --------------------------------------------------------

    save_visualization(
        image=image,
        predicted_label=predicted_label,
        probabilities=probabilities,
        output_path=args.output,
        model_name=args.model,
        true_label=true_label,
    )

    print(f"\nVisualization saved to: {args.output}")
    print(
        "\nResearch prototype only. "
        "Not validated for clinical diagnosis."
    )


if __name__ == "__main__":
    main()

